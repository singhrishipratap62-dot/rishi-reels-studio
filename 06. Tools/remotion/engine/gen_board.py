#!/usr/bin/env python3
"""Copy the pack's board engine (01. Styles/Consulting Case/engine/board.html) into the Remotion comp, unchanged.
board.html stays the single source of truth for the board look + timing math; re-run after editing it.
usage: python3 gen_board.py  -> src/CaseReel/boardSrc.ts"""
import json, os, re
here = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(here, '../../../01. Styles/Consulting Case/engine/board.html'), encoding='utf-8').read()
css = re.search(r'<style>(.*?)</style>', html, re.S).group(1)
body = re.search(r'<body>(.*?)<script>', html, re.S).group(1)
script = re.search(r'<script>(.*?)</script>', html, re.S).group(1)
# scope the page-level rules to the comp's root node so they don't leak into Remotion Studio
css = css.replace('*{box-sizing', '.cr-root *{box-sizing').replace('html,body{', '.cr-root{')
with open(os.path.join(here, 'src/CaseReel/boardSrc.ts'), 'w', encoding='utf-8') as f:
    f.write('// GENERATED by gen_board.py from 01. Styles/Consulting Case/engine/board.html. Do not edit.\n')
    for k, v in (('BOARD_CSS', css), ('BOARD_BODY', body), ('BOARD_SCRIPT', script)):
        f.write(f'export const {k} = {json.dumps(v, ensure_ascii=False)};\n')
print('boardSrc.ts written')
