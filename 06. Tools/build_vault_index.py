#!/usr/bin/env python3
"""Refresh the Obsidian project lists: `03. Projects/Projects Index.md` and the
project block inside each `01. Styles/<style>/Hub - *.md`.
Read-only on project folders; only rewrites those index notes.
usage: build_vault_index.py [--dry]
"""
import os, re, sys


def _studio_root(p=os.path.dirname(os.path.abspath(__file__))):
    while not os.path.exists(os.path.join(p, ".studio-root")):
        if p == os.path.dirname(p):
            raise SystemExit("studio root not found")
        p = os.path.dirname(p)
    return p


ROOT = _studio_root()
PROJ = os.path.join(ROOT, "03. Projects")
START, END = "<!-- projects:start -->", "<!-- projects:end -->"
DRY = "--dry" in sys.argv


def project_rows(style):
    base = os.path.join(PROJ, style)
    rows = []
    for name in sorted(os.listdir(base)):
        full = os.path.join(base, name)
        if name.startswith(".") or not os.path.isdir(full):
            continue
        m = re.match(r"(R\d+)_", name)
        reel = m.group(1) if m else ""
        plan = os.path.join(full, "plan.md")
        link = f"[[03. Projects/{style}/{name}/plan|{name}]]" if os.path.exists(plan) else name
        rows.append((reel, link, "plan" if os.path.exists(plan) else ""))
    return rows


def write(path, text):
    if DRY:
        print(f"[dry] would write {os.path.relpath(path, ROOT)}")
        return
    with open(path, "w") as f:
        f.write(text)


def main():
    styles = [d for d in sorted(os.listdir(PROJ)) if os.path.isdir(os.path.join(PROJ, d))]
    out = ["---", "type: index", "---", "# Projects index", "",
           "Generated by `06. Tools/build_vault_index.py`; don't edit by hand. Links resolve only where a `plan.md` exists.", ""]
    for s in styles:
        out += [f"## {s}", "", "| Reel | Project | Plan |", "|---|---|---|"]
        out += [f"| {r} | {l} | {p} |" for r, l, p in project_rows(s)]
        out.append("")
    write(os.path.join(PROJ, "Projects Index.md"), "\n".join(out))

    styles_dir = os.path.join(ROOT, "01. Styles")
    for st in sorted(os.listdir(styles_dir)):
        d = os.path.join(styles_dir, st)
        if not os.path.isdir(d):
            continue
        hubs = [f for f in os.listdir(d) if f.startswith("Hub - ") and f.endswith(".md")]
        if not hubs:
            continue
        hub = os.path.join(d, hubs[0])
        text = open(hub).read()
        if START not in text:
            continue
        key = re.search(r"^projects_folder: (.+)$", text, re.M)
        if not key or not os.path.isdir(os.path.join(PROJ, key.group(1))):
            continue
        rows = project_rows(key.group(1))
        block = START + "\n" + ("\n".join(f"- {l}" + (f" ({r})" if r else "") for r, l, _ in rows) or "_none yet_") + "\n" + END
        text = re.sub(re.escape(START) + ".*?" + re.escape(END), lambda _: block, text, flags=re.S)
        write(hub, text)


if __name__ == "__main__":
    main()
